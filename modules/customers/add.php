<?php
require_once __DIR__ . '/../../includes/auth.php';
requireRole('admin', 'staff');
require_once __DIR__ . '/../../includes/internet_service.php';
require_once __DIR__ . '/../../includes/customer_validation.php';

$pdo = getDbConnection();
$plans = $pdo->query("SELECT * FROM internet_plans WHERE enabled=1 ORDER BY category,speed_mbps")->fetchAll();

$errors = [];
$values = [
    'first_name' => '',
    'middle_initial' => '',
    'last_name' => '',
    'suffix' => '',
    'contact_number' => '',
    'email' => '',
    'address' => '',
    'plan_id' => '',
];

if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    if (!verifyCsrfToken($_POST['csrf_token'] ?? null)) {
        $errors[] = 'Invalid request. Please try again.';
    } else {
        $first = trim($_POST['first_name'] ?? '');
        $middle = trim($_POST['middle_initial'] ?? '');
        $last = trim($_POST['last_name'] ?? '');
        $suffix = trim($_POST['suffix'] ?? '');
        $contact = normalizeContactNumber($_POST['contact_number'] ?? '');
        $email = trim($_POST['email'] ?? '');
        $address = trim($_POST['address'] ?? '');
        $planId = trim($_POST['plan_id'] ?? '');
        $namePattern = "/^[\p{L}][\p{L} .\-]{0,49}$/u";

        if ($first === '') $errors[] = 'First name is required.';
        if ($last === '') $errors[] = 'Last name is required.';
        $hasNameDigit = false;
        foreach ([$first, $middle, $last, $suffix] as $namePart) {
            if (preg_match('/\d/', $namePart)) $hasNameDigit = true;
        }
        if ($hasNameDigit) {
            $errors[] = 'Names must contain letters only.';
        } else {
            if ($first !== '' && !preg_match($namePattern, $first)) $errors[] = 'First name may only contain letters, spaces, periods, and hyphens.';
            if ($last !== '' && !preg_match($namePattern, $last)) $errors[] = 'Last name may only contain letters, spaces, periods, and hyphens.';
            if ($middle !== '' && !preg_match('/^\p{L}$/u', $middle)) $errors[] = 'Middle initial must be a single letter.';
            if ($suffix !== '' && !in_array($suffix, CUSTOMER_SUFFIXES, true)) $errors[] = 'Select a valid suffix.';
        }
        if ($contact === '') $errors[] = 'Contact number is required.';
        elseif (!validPhMobile($contact)) $errors[] = 'Contact number must be a Philippine mobile number in 09XXXXXXXXX format.';
        if ($email === '') $errors[] = 'Email address is required.';
        elseif (!filter_var($email, FILTER_VALIDATE_EMAIL)) $errors[] = 'Email address is invalid.';
        if (!$errors) {
            if (($dup = findDuplicateCustomer($pdo, 'contact_number', $contact))) $errors[] = 'Contact number ' . $contact . ' is already used by customer ' . $dup['account_number'] . ' (' . $dup['full_name'] . ').';
            if (($dup = findDuplicateCustomer($pdo, 'email', $email))) $errors[] = 'Email address ' . $email . ' is already used by customer ' . $dup['account_number'] . ' (' . $dup['full_name'] . ').';
        }

        $middle = $middle === '' ? null : strtoupper(rtrim($middle, '.'));
        $values = [
            'first_name' => $first,
            'middle_initial' => $middle ?? '',
            'last_name' => $last,
            'suffix' => $suffix,
            'contact_number' => $contact,
            'email' => $email,
            'address' => $address,
            'plan_id' => $planId,
            'full_name' => fullNameFromParts($first, $middle ?? '', $last, $suffix),
        ];

        if (!ctype_digit($values['plan_id']) || !in_array((int)$values['plan_id'], array_map('intval', array_column($plans,'id')), true)) $errors[] = 'Select an available internet plan.';

        if (!$errors) {
            $pdo->beginTransaction();
            try {
                // Account number is generated by the system, not entered manually.
                // The customer record itself holds no single service field; services
                // are tracked per-subscription in customer_services below.
                $stmt = $pdo->prepare('INSERT INTO customers (account_number, full_name, first_name, middle_initial, last_name, suffix, contact_number, email, address, status) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)');
                $temporaryAccount = 'PENDING-' . bin2hex(random_bytes(8));
                $stmt->execute([
                    $temporaryAccount,
                    $values['full_name'],
                    $values['first_name'],
                    $values['middle_initial'],
                    $values['last_name'],
                    $values['suffix'] !== '' ? $values['suffix'] : null,
                    $values['contact_number'],
                    $values['email'],
                    $values['address'],
                    'active',
                ]);
                $customerId = (int) $pdo->lastInsertId();
                $accountNumber = 'CUST-' . str_pad((string) $customerId, 6, '0', STR_PAD_LEFT);
                $pdo->prepare('UPDATE customers SET account_number = ? WHERE id = ?')->execute([$accountNumber, $customerId]);
                if ($values['plan_id'] !== '') {
                    $planQuery = $pdo->prepare('SELECT id,monthly_rate FROM internet_plans WHERE id=? AND enabled=1');
                    $planQuery->execute([$values['plan_id']]);
                    $plan = $planQuery->fetch();
                    if (!$plan) throw new RuntimeException('Select an available internet plan.');
                    $serviceId = internetServiceId($pdo);
                    $pdo->prepare('INSERT INTO customer_services (customer_id,service_id,plan_id,billing_amount,start_date,next_billing_date,status) VALUES (?,?,?,?,CURDATE(),CURDATE(),?)')->execute([$customerId,$serviceId,$plan['id'],$plan['monthly_rate'],'active']);
                    $subscriptionId=(int)$pdo->lastInsertId();
                    $pdo->prepare('UPDATE customer_services SET service_account_number=? WHERE id=?')->execute(['ACC-'.str_pad((string)$subscriptionId,6,'0',STR_PAD_LEFT),$subscriptionId]);
                }
                $pdo->commit();
            } catch (Throwable $exception) {
                if ($pdo->inTransaction()) $pdo->rollBack();
                $errors[] = customerWriteError($exception);
            }
        }
        if (!$errors) {
            header('Location: index.php?msg=' . urlencode('Customer added successfully.'));
            exit;
        }
    }
}

